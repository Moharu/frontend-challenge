import {
  type CheckoutCollectorData,
  type CheckoutCollectorSnapshot,
  type OrderCheckoutSnapshot,
  type OrderWalletSnapshot,
} from "./checkout";
import { integer, record, timestamp, type Eth } from "./common";
import { isEth } from "./eth";
import type { Amounts } from "./quotes";
import { networkNames, walletProviders } from "./wallets";
export type OrderStatus = "pending" | "confirmed" | "declined";
// The idempotency key travels in the Idempotency-Key header, not in the JSON.
// The network is not sent: the server resolves it from the wallet, as for the
// quote.
export interface CreateOrderBody {
  quoteId: string;
  quoteVersion: number;
  walletId: string;
  collector: CheckoutCollectorData;
  collectorNote?: string;
}
export interface CreateOrderRequest {
  idempotencyKey: string;
  body: CreateOrderBody;
}
export const idempotencyHeader = "Idempotency-Key";
// Keys are generated by the client (UUID v4 or similar opaque text).
export const idempotencyKeyPattern = /^[A-Za-z0-9-]{16,64}$/;
// Snapshot of a purchased line, taken when the order is created: later
// catalog changes (price, name, artwork) never alter it.
export interface PurchasedItem {
  readonly nftId: string;
  readonly editionId: string;
  readonly name: string;
  readonly editionLabel: string;
  readonly tokenId: string;
  readonly artwork: string;
  readonly quantity: number;
  readonly unitPriceEth: Eth;
  readonly lineTotalEth: Eth;
}
export interface OrderAmounts extends Amounts {
  readonly couponCode: string | null;
}
export interface OrderReceipt extends OrderCheckoutSnapshot {
  readonly orderId: string;
  readonly confirmedAt: string;
  // Simulated transaction hash: 0x + 64 hexadecimal characters.
  readonly transactionReference: string;
  readonly items: ReadonlyArray<PurchasedItem>;
  readonly amounts: Readonly<OrderAmounts>;
}
export interface Order extends OrderCheckoutSnapshot {
  id: string;
  userId: string;
  version: number;
  status: OrderStatus;
  quoteId: string;
  quoteVersion: number;
  items: ReadonlyArray<PurchasedItem>;
  amounts: Readonly<OrderAmounts>;
  createdAt: string;
  updatedAt: string;
  receipt: OrderReceipt | null;
  // Readable reason, set only when declined.
  declineCode: string | null;
}
export const transactionReferencePattern = /^0x[0-9a-f]{64}$/;
// Terminal states never change again.
export const isTerminal = (status: OrderStatus) => status !== "pending";
function isItem(value: unknown): value is PurchasedItem {
  return (
    record(value) &&
    ["nftId", "editionId", "name", "editionLabel", "tokenId", "artwork"].every(
      (key) => typeof value[key] === "string",
    ) &&
    integer(value.quantity, 1) &&
    isEth(value.unitPriceEth) &&
    isEth(value.lineTotalEth)
  );
}
function isAmounts(value: unknown): value is OrderAmounts {
  return (
    record(value) &&
    isEth(value.subtotalEth) &&
    isEth(value.discountEth) &&
    isEth(value.networkFeeEth) &&
    isEth(value.totalEth) &&
    (value.couponCode === null || typeof value.couponCode === "string")
  );
}
const nullableText = (value: unknown) =>
  value === null || typeof value === "string";
function isCollector(value: unknown): value is CheckoutCollectorSnapshot {
  return (
    record(value) &&
    ["displayName", "username", "email", "profileName"].every(
      (key) => typeof value[key] === "string",
    ) &&
    ["referralCode", "ensName", "secondaryAddressOrEns"].every((key) =>
      nullableText(value[key]),
    )
  );
}
function isWalletSnapshot(value: unknown): value is OrderWalletSnapshot {
  return (
    record(value) &&
    typeof value.walletId === "string" &&
    integer(value.walletVersion, 1) &&
    typeof value.address === "string" &&
    typeof value.network === "string" &&
    value.network in networkNames &&
    walletProviders.includes(value.provider as never)
  );
}
function isSnapshot(value: Record<string, unknown>) {
  return (
    isCollector(value.collector) &&
    isWalletSnapshot(value.wallet) &&
    nullableText(value.collectorNote)
  );
}
export function isReceipt(value: unknown): value is OrderReceipt {
  return (
    record(value) &&
    typeof value.orderId === "string" &&
    timestamp(value.confirmedAt) &&
    typeof value.transactionReference === "string" &&
    transactionReferencePattern.test(value.transactionReference) &&
    Array.isArray(value.items) &&
    value.items.length > 0 &&
    value.items.every(isItem) &&
    isAmounts(value.amounts) &&
    isSnapshot(value)
  );
}
export function isOrder(value: unknown): value is Order {
  return (
    record(value) &&
    typeof value.id === "string" &&
    typeof value.userId === "string" &&
    integer(value.version, 1) &&
    (value.status === "pending" ||
      value.status === "confirmed" ||
      value.status === "declined") &&
    typeof value.quoteId === "string" &&
    integer(value.quoteVersion, 1) &&
    Array.isArray(value.items) &&
    value.items.every(isItem) &&
    isAmounts(value.amounts) &&
    timestamp(value.createdAt) &&
    timestamp(value.updatedAt) &&
    (value.status === "confirmed"
      ? isReceipt(value.receipt)
      : value.receipt === null) &&
    (value.status === "declined"
      ? typeof value.declineCode === "string"
      : value.declineCode === null) &&
    isSnapshot(value)
  );
}
// Canonical JSON (keys sorted at every level), used to compare the bodies of
// requests sharing an idempotency key regardless of property order.
export function canonicalJson(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(",")}]`;
  if (record(value))
    return `{${Object.keys(value)
      .filter((key) => value[key] !== undefined)
      .sort()
      .map((key) => `${JSON.stringify(key)}:${canonicalJson(value[key])}`)
      .join(",")}}`;
  return JSON.stringify(value);
}
